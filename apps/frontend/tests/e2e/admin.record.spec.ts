test('after 180 s the job is slow, and Check again polls it again (REQ-041)', async ({
  page,
}) => {
  await page.clock.install();
  await openRecordAnswer(page);
  await setText(page, 'سلام #slow');
  await recordAndStop(page);
  await expect(page.getByText('Processing the recording')).toBeVisible();

  await page.clock.fastForward('03:05');

  await expect(
    page.getByText(
      'The recording is still being processed. Check again in a minute.',
    ),
  ).toBeVisible();
  await page.getByRole('button', { name: 'Check again' }).click();
  await expect(page.getByText('Processing the recording')).toBeVisible();
});

test('Record this answer on a ready entry records its text and attaches the video (REQ-074)', async ({
  page,
}) => {
  await login(page);
  await page.getByRole('link', { name: 'Answer library' }).click();
  await page.getByRole('grid').getByText('C4Q02', { exact: true }).click();
  await page
    .getByRole('dialog', { name: 'Answer C4Q02' })
    .getByRole('button', { name: 'Record this answer' })
    .click();

  const composer = page.getByRole('textbox', { name: 'Persian text' });
  await expect(composer).toHaveValue(READY_TEXT);
  await expect(composer).toHaveAttribute('readonly', '');
  // The screen's own button comes first. Once the recording is done, the unsaved list below
  // offers an Attach for the same entry too.
  const attach = page
    .getByRole('button', { name: 'Attach to this answer' })
    .first();
  await expect(attach).toBeDisabled();

  await recordAndStop(page);
  await expect(
    page.getByText('The recording is ready. Save it to the library.'),
  ).toBeVisible(JOB_END);
  await attach.click();

  const panel = page.getByRole('dialog', { name: 'Answer C4Q02' });
  await expect(panel.getByText('Waiting for video review')).toBeVisible();
});

test('a recording left behind by a reload is listed, and attaches to its ready entry (REQ-042)', async ({
  page,
}) => {
  await login(page);
  await page.goto('/library/record?entry=mock-library-ready&key=C4Q02');
  await expect(page.getByRole('textbox', { name: 'Persian text' })).toHaveValue(
    READY_TEXT,
  );
  await recordAndStop(page);
  await expect(
    page.getByText('The recording is ready. Save it to the library.'),
  ).toBeVisible(JOB_END);

  // A client-side move, so the in-page mock keeps its recording: a real reload would reset it.
  await page.getByRole('link', { name: 'Answer library' }).first().click();
  await page.getByRole('link', { name: 'Record answer' }).click();

  const unsaved = page.getByRole('region', {
    name: 'Finished recordings not in the library',
  });
  const row = unsaved.getByRole('listitem').filter({ hasText: READY_TEXT });
  await row.getByRole('button', { name: 'Attach to this answer' }).click();

  const panel = page.getByRole('dialog', { name: 'Answer C4Q02' });
  await expect(panel.getByText('Waiting for video review')).toBeVisible();
});

test('the screen renders right to left in Persian at phone width', async ({
  page,
}) => {
  await openRecordAnswer(page);
  // Phone width only after login: the sidebar link sits behind the menu button there.
  await page.setViewportSize({ width: 390, height: 844 });

  await page.evaluate(() => {
    const saved = JSON.parse(
      window.localStorage.getItem('settings') ?? '{}',
    ) as object;
    window.localStorage.setItem(
      'settings',
      JSON.stringify({ ...saved, language: 'fa' }),
    );
  });
  await page.reload();

  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl');
  await expect(
    page.getByRole('heading', { name: 'ضبط پاسخ', level: 1 }),
  ).toBeVisible();
  const overflow = await page.evaluate(
    () =>
      document.documentElement.scrollWidth -
      document.documentElement.clientWidth,
  );
  expect(overflow).toBeLessThanOrEqual(0);
});
