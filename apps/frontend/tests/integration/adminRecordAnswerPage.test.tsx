let requests: InternalAxiosRequestConfig[] = [];
let override:
  | ((config: InternalAxiosRequestConfig) => AxiosResponse | undefined)
  | undefined;

function reply(
  config: InternalAxiosRequestConfig,
  data: unknown,
  status = 200,
): AxiosResponse {
  return { data, status, statusText: 'OK', headers: {}, config };
}

function errorReply(
  config: InternalAxiosRequestConfig,
  status: number,
  code: string,
) {
  return reply(
    config,
    { error: { code, message: 'Fixed English text.', retryable: false } },
    status,
  );
}

beforeEach(() => {
  vi.useFakeTimers({ shouldAdvanceTime: true });
  installMockApi(apiClient, { delayMs: 0 });
  const mockAdapter = apiClient.defaults.adapter as AxiosAdapter;
  requests = [];
  override = undefined;
  apiClient.defaults.adapter = async (config) => {
    requests.push(config);
    const answer = override?.(config);
    if (answer) {
      if (answer.status >= 400) {
        throw new AxiosError(
          'failed',
          'ERR_BAD_RESPONSE',
          config,
          null,
          answer,
        );
      }
      return answer;
    }
    return mockAdapter(config);
  };
  resetMockLibrary();
  mockSession.set('u-admin');
});

