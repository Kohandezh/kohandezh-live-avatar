function setupUser(): UserEvent {
  return userEvent.setup({ advanceTimers: vi.advanceTimersByTime });
}

async function advance(ms: number) {
  await act(async () => {
    await vi.advanceTimersByTimeAsync(ms);
  });
}

function renderAdmin(route: string, language: 'en' | 'fa' = 'en') {
  return renderWithProviders(
    <Routes>
      <Route path="/library" element={<AdminLibraryPage />} />
      <Route path="/library/record" element={<AdminRecordAnswerPage />} />
    </Routes>,
    {
      route,
      locale: language,
      preloadedState: { settings: { ...loadInitialSettings(), language } },
    },
  );
}

function requestsTo(method: string, path: RegExp) {
  return requests.filter(
    (config) =>
      config.method?.toLowerCase() === method && path.test(config.url ?? ''),
  );
}

async function setComposerText(user: UserEvent, text: string) {
  const field = screen.getByRole('textbox', { name: 'Persian text' });
  await user.clear(field);
  await user.click(field);
  await user.paste(text);
}

async function startSession(user: UserEvent) {
  await user.click(screen.getByRole('button', { name: 'Start avatar' }));
  await screen.findByRole('button', { name: 'Close session' });
  await waitFor(() =>
    expect(screen.getByRole('button', { name: 'Start avatar' })).toBeDisabled(),
  );
}

/** Starts and stops a recording, so its finalize job is queued. */
const NEEDS_AUDIO = 'Generate the audio first, so its length can be checked.';

/** Generates the audio of the text on screen, which Record needs (ruling 5). */
async function generateAudio(user: UserEvent) {
  await user.click(screen.getByRole('button', { name: 'Generate audio' }));
  await screen.findByText(/Generated by ElevenLabs/);
}

async function recordAndStop(user: UserEvent) {
  await startSession(user);
  await generateAudio(user);
  await user.click(screen.getByRole('button', { name: 'Start recording' }));
  await user.click(
    await screen.findByRole('button', { name: 'Stop recording' }),
  );
}

/** The mock job answers queued, then running, then done, one step per poll (2 s apart). */
async function waitForJobDone() {
  expect(
    await screen.findByText('Waiting to process the recording'),
  ).toBeInTheDocument();
  await advance(2000);
  expect(
    await screen.findByText('Processing the recording'),
  ).toBeInTheDocument();
  await advance(2000);
  expect(
    await screen.findByText('The recording is ready. Save it to the library.'),
  ).toBeInTheDocument();
}

function saveForm() {
  return screen.getByRole('form', { name: 'Save to library' });
}

async function fillSaveForm(user: UserEvent, form: HTMLElement, key?: string) {
  await user.type(
    within(form).getByRole('textbox', { name: 'Question' }),
    'پرسش تازه',
  );
  await user.type(
    within(form).getByRole('textbox', { name: 'Category number' }),
    '5',
  );
  await user.type(
    within(form).getByRole('textbox', { name: 'Category title' }),
    'دسته پنج',
  );
  if (key)
    await user.type(within(form).getByRole('textbox', { name: /Key/ }), key);
}

/**
 * The screen's own Attach button. Once the recording is done it is also in the unsaved list,
 * which offers its own Attach for the same entry.
 */
function entryAttachButton() {
  const unsaved = screen.queryByRole('region', {
    name: 'Finished recordings not in the library',
  });
  const button = screen
    .getAllByRole('button', { name: 'Attach to this answer' })
    .find((candidate) => !unsaved?.contains(candidate));
  if (!button) throw new Error('the screen has no Attach button of its own');
  return button;
}

/** Records `text` through the mock API, so it is a finished recording no entry uses. */
async function makeFinishedRecording(text: string) {
  const session = await apiClient.post('/api/avatar/session', {});
  const video = await apiClient.post('/api/assets/generate-video', {
    session_id: session.data.id,
    asset_id: 'AVATAR_20260928090000',
    text,
  });
  const { data } = await apiClient.post(
    `/api/assets/video/${video.data.id}/finalize`,
  );
  for (let poll = 0; poll < 3; poll += 1)
    await apiClient.get(`/api/jobs/${data.jobId}`);
  requests = [];
}

